"""Lower Xuzhou's bookmark population without changing other native populations."""
from pathlib import Path
from decimal import Decimal,ROUND_DOWN
import json,re
from pdxscript import blocks,tokens

def apply(out,root,game):
    out,root,game=map(Path,(out,root,game))
    manifest=json.loads((out/'build_manifest.json').read_text(encoding='utf-8-sig'))
    country=next(c for c in manifest['countries'] if c['tag']=='BAP');places=set(country['locations'])
    source=game/'main_menu/setup/1337/06_pops.txt';native=source.read_text(encoding='utf-8-sig')
    _,_,a,z,_=blocks(native,0)[0];body=native[a:z];entries=blocks(body,0)
    old=sum(Decimal(v) for k,_,a,z,_ in entries if k in places for v in re.findall(r'\bsize\s*=\s*(\d+(?:\.\d+)?)',body[a:z]))
    target=Decimal('95');factor=target/old;remaining=target;seen=0
    count=sum(len(re.findall(r'\bsize\s*=',body[a:z])) for k,_,a,z,_ in entries if k in places)
    lines=[];changes=[]
    for k,_,a,z,_ in entries:
        text=body[a:z];before=text
        if k in places:
            def scale(q):
                nonlocal remaining,seen
                seen+=1
                value=(Decimal(q[1])*factor).quantize(Decimal('0.001'),rounding=ROUND_DOWN) if seen<count else remaining
                assert value>0;remaining-=value
                return 'size = '+format(value,'f')
            text=re.sub(r'\bsize\s*=\s*(\d+(?:\.\d+)?)',scale,text)
            # Only population sizes may change, not types, cultures, religions or groups.
            erase=lambda t:re.sub(r'\bsize\s*=\s*(\d+(?:\.\d+)?)','size = POPULATION_SIZE',t)
            assert [x.value for x in tokens(erase(before))]==[x.value for x in tokens(erase(text))]
            changes.append(dict(location=k,before_k=sum(Decimal(v) for v in re.findall(r'\bsize\s*=\s*(\d+(?:\.\d+)?)',before)),after_k=sum(Decimal(v) for v in re.findall(r'\bsize\s*=\s*(\d+(?:\.\d+)?)',text))))
        lines.append(k+' = { '+' '.join(x.value for x in tokens(text))+' }')
    assert remaining==0 and len(changes)==5
    output='''# Generated by build_opening_population.py from the installed native table.
# Only BAP's five locations are scaled. Other locations retain their token sequences.
locations = {
'''+ '\n'.join(lines)+'\n}\n'
    file=out/'main_menu/setup/1337/06_pops.txt';file.write_text(output,encoding='utf-8')
    report=dict(country='BAP',name=country['name'],before_people=int(old*1000),after_people=95000,locations=[{k:float(v) if isinstance(v,Decimal) else v for k,v in c.items()} for c in changes],native_locations=len(entries),method='Bookmark setup data; no game-start population effect',other_locations_unchanged=True)
    return report
