"""Bookmark population adjustments, before country selection; never a first-day effect."""
from pathlib import Path
from decimal import Decimal, ROUND_DOWN
import json
import re
from pdxscript import blocks, tokens

# Values are thousands of people, relative to the unmodified native table.
COUNTRY_DELTAS = {'BAB': 20, 'BBU': 10, 'CKL': -10, 'GYE': -10, 'BBQ': -20}
FIXED_POPULATIONS = {'BAP': 95}
NAMES = {'CKL': '明正', 'GYE': '嘉绒'}


def owned_locations(setup, wanted):
    result = {}
    for tag, _, start, end, _ in blocks(setup, 2):
        if tag not in wanted:
            continue
        body = setup[start:end]
        result[tag] = []
        for key, _, a, b, _ in blocks(body, 0):
            if key.startswith('own_'):
                result[tag].extend(t.value for t in tokens(body[a:b]))
    assert set(result) == set(wanted) and all(result.values())
    return result


def population(text):
    return sum((Decimal(v) for v in re.findall(r'\bsize\s*=\s*(\d+(?:\.\d+)?)', text)), Decimal(0))


def apply(out, root, game):
    out, root, game = map(Path, (out, root, game))
    manifest = json.loads((out / 'build_manifest.json').read_text(encoding='utf-8-sig'))
    setup = (out / 'main_menu/setup/1337/10_countries.txt').read_text(encoding='utf-8-sig')
    places = owned_locations(setup, set(COUNTRY_DELTAS) | set(FIXED_POPULATIONS))
    owner = {location: tag for tag, locations in places.items() for location in locations}
    assert len(owner) == sum(map(len, places.values())), 'Population adjustment countries overlap'
    native = (game / 'main_menu/setup/1337/06_pops.txt').read_text(encoding='utf-8-sig')
    _, _, a, z, _ = blocks(native, 0)[0]
    body = native[a:z]
    entries = blocks(body, 0)
    old = {tag: sum((population(body[a:z]) for location, _, a, z, _ in entries if owner.get(location) == tag), Decimal(0)) for tag in places}
    target = {tag: Decimal(FIXED_POPULATIONS[tag]) if tag in FIXED_POPULATIONS else value + Decimal(COUNTRY_DELTAS[tag]) for tag, value in old.items()}
    assert all(value > 0 for value in target.values())
    allocations = {}
    for tag in places:
        source = [Decimal(v) for location, _, a, z, _ in entries if owner.get(location) == tag for v in re.findall(r'\bsize\s*=\s*(\d+(?:\.\d+)?)', body[a:z])]
        exact = [value * target[tag] / old[tag] for value in source]
        rounded = [value.quantize(Decimal('0.001'), rounding=ROUND_DOWN) for value in exact]
        assert all(value > 0 for value in rounded), 'Cannot preserve a positive population group at person precision'
        remainder = int((target[tag] - sum(rounded)) / Decimal('0.001'))
        order = sorted(range(len(source)), key=lambda i: exact[i] - rounded[i], reverse=True)
        for i in order[:remainder]:
            rounded[i] += Decimal('0.001')
        assert sum(rounded) == target[tag]
        allocations[tag] = iter(rounded)
    lines, changes = [], {tag: [] for tag in places}
    for location, _, a, z, _ in entries:
        text = body[a:z]
        before = text
        if location in owner:
            tag = owner[location]
            text = re.sub(r'\bsize\s*=\s*(\d+(?:\.\d+)?)', lambda _: 'size = ' + format(next(allocations[tag]), 'f'), text)
            erase = lambda value: re.sub(r'\bsize\s*=\s*(\d+(?:\.\d+)?)', 'size = POPULATION_SIZE', value)
            assert [t.value for t in tokens(erase(before))] == [t.value for t in tokens(erase(text))]
            changes[tag].append(dict(location=location, before_k=float(population(before)), after_k=float(population(text))))
        lines.append(location + ' = { ' + ' '.join(t.value for t in tokens(text)) + ' }')
    for tag, iterator in allocations.items():
        assert next(iterator, None) is None and len(changes[tag]) == len(places[tag])
    output = ('# Generated by build_opening_population.py from the installed native table.\n'
              '# Country totals change only for BAP, BAB, BBU, CKL, GYE and BBQ; pop identities are preserved.\n'
              'locations = {\n' + '\n'.join(lines) + '\n}\n')
    (out / 'main_menu/setup/1337/06_pops.txt').write_text(output, encoding='utf-8', newline='\n')
    names = {country['tag']: country['name'] for country in manifest['countries']} | NAMES
    adjustments = [dict(country=tag, name=names[tag], before_people=int(old[tag] * 1000), after_people=int(target[tag] * 1000),
                        delta_people=int((target[tag] - old[tag]) * 1000), locations=changes[tag]) for tag in places]
    legacy = next(row for row in adjustments if row['country'] == 'BAP')
    return dict(legacy, adjustments=adjustments, requested_deltas_people={tag: value * 1000 for tag, value in COUNTRY_DELTAS.items()},
                native_locations=len(entries), method='Bookmark setup data; proportional groups with largest-remainder person rounding; no game-start effect',
                other_locations_unchanged=True)
